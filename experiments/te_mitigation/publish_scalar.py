"""Sanitized scalar prototype results and actual emitted entry-point bodies."""

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from publish import clean_graph, pick, read, sha, validate_public_text, write  # noqa: E402


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("root", type=Path)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    processes = []
    for repeat in (0, 1):
        folder = args.root / str(repeat)
        result = read(folder / "data/result.json")
        identity = read(folder / "data/identity.json")
        completed = read(folder / "finished.json")
        if completed["exit_code"] or completed["accounting"]["active_processes"]:
            raise ValueError("Scalar prototype incomplete")
        if not result["gpu_eager_cpu_staged_exact"]:
            raise ValueError("Independent CPU reference failed")
        rows = []
        for row in result["rows"]:
            if any(row[k]["status"] != "PASS" for k in ("hip_before", "hip_after")):
                raise ValueError("HIP failed")
            rows.append(
                pick(
                    row,
                    "name ordinal input output operators different_elements max_abs "
                    "first_differing_flat_index cpu_staged_exact "
                    "cpu_single_float_expression_exact hip_before hip_after",
                )
                | {"graph": clean_graph(row["graph"])}
            )
        emitted = []
        depth = 0
        for raw in (folder / "stderr.log").read_text("utf-8").splitlines():
            if not raw.startswith("[DEBUG cuda_codegen"):
                continue
            line = re.sub(r"^\[DEBUG [^\]]+\] ?", "", raw)
            if line.startswith("void fused_"):
                depth = 0
                emitted.append([])
            if emitted and (depth > 0 or line.startswith("void fused_")):
                emitted[-1].append(line)
                depth += line.count("{") - line.count("}")
        if len(emitted) != 2:
            raise ValueError("Expected both emitted prototype kernels")
        processes.append(
            dict(
                repeat=repeat,
                pid=identity["pid"],
                wheel_sha256=identity["wheel_sha256"],
                producer_sha256=result["producer_sha256"],
                declaration_sha256=result["declaration_sha256"],
                input_artifact_sha256=result["input_artifact_sha256"],
                source=result["source"],
                source_declaration=result["source_declaration"],
                gpu_eager_cpu_staged_exact=True,
                eager=result["eager"],
                cpu_staged=result["cpu_staged"],
                cpu_single_float=result["cpu_single_float"],
                rows=rows,
                emitted_entry_points=["\n".join(lines) for lines in emitted],
                stderr_sha256=sha(folder / "stderr.log"),
                accounting=completed["accounting"],
            )
        )
    payload = dict(
        producer_sha256=sha(__file__),
        processes=processes,
        verdict="Both prototypes rejected for preserving original eager BF16 semantics",
        license_note=(
            "Entry-point bodies generated by unchanged PyTorch; PyTorch license retained in wheel"
        ),
    )
    import json

    validate_public_text(json.dumps(payload))
    write(args.output, payload)


if __name__ == "__main__":
    main()
